export function getTonePrompt(character, question) {
  return question.prompt[character.tone] || question.prompt.mystic;
}

export function pickLine(characterId, group, index = 0) {
  const lines = characterLineBanks[characterId]?.[group] || [];
  if (!lines.length) return '';
  return lines[index % lines.length];
}
